from __future__ import annotations

import re
from typing import Callable


def _norm(text: str) -> str:
    t = (text or "").strip()
    for a, b in (("أ", "ا"), ("إ", "ا"), ("آ", "ا"), ("ة", "ه"), ("ى", "ي"), ("ؤ", "و"), ("ئ", "ي")):
        t = t.replace(a, b)
    t = re.sub(r"\s+", " ", t)
    return t


