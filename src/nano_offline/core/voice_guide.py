def guide_for_section(section: str) -> str:
    key = (section or "dashboard").lower().strip()
    if key in SECTION_GUIDE:
        return SECTION_GUIDE[key]
    return SECTION_GUIDE.get("dashboard", "أنت في نانو. قل مساعدة أو اشرح الشاشة للتوجيه.")


def match_guide(text: str, *, section: str = "") -> tuple[str, str | None] | None:
    """Return (answer, navigate_target|None) if text looks like a help question."""
    raw = (text or "").strip()
    t = _norm(raw)
    if not t:
        return None

    # Explicit: اشرح / علمني / ماذا أفعل هنا / وين أنا
    if any(k in t for k in ("اشرح الشاشه", "اشرح الشاشة", "علمني هنا", "ماذا افعل هنا", "وش افعل هنا", "وين انا", "أين أنا", "ما هذه الشاشه", "ما هذه الشاشة")):
        return guide_for_section(section), None

    if any(k in t for k in ("اشرح", "علمني", "كيف استخدم", "دليل", "توجيه", "ساعدني")) and len(t) < 24:
        return guide_for_section(section), None

    for keys, answer in WHAT_IS:
        if any(_norm(k) in t for k in keys):
            return answer, None

    for keys, answer, target in HOWTO:
        if any(_norm(k) in t for k in keys):
            return answer, target

    # Soft how-to: starts with كيف / وين / عوز / بدي
    if t.startswith(("كيف ", "وين ", "أين ", "بدي ", "بريد ", "اريد ", "أريد ", "عوز ", "ممكن ")):
        # try partial keyword overlap with HOWTO
        for keys, answer, target in HOWTO:
            for k in keys:
                kn = _norm(k)
                # shared token
                if any(tok in t for tok in kn.split() if len(tok) > 2):
                    return answer, target
        return (
            "يمكنني توجيهك داخل نانو: قل كيف أبيع، كيف أضيف مادة، كيف أجرد، كيف نسخة احتياطية، "
            "أو اشرح الشاشة لشرح مكانك الحالي. وللتنفيذ المباشر: بيع سريع، مواد، مالية، تقارير.",
            None,
        )

    return None


